# Standard predictable exit codes
EXIT_SUCCESS = 0
EXIT_USAGE_ERROR = 1
EXIT_FILE_READ_ERROR = 2
EXIT_PROCESSING_ERROR = 3


def read_config_file(filepath: str) -> tuple[str, int]:
    """Read a configuration file safely supporting UTF-8, UTF-8-BOM, and Latin-1 fallbacks.

    Returns:
        (config_text, file_size_bytes)

    Raises:
        FileNotFoundError, PermissionError, IsADirectoryError, ValueError
    """
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Configuration file not found: {filepath}")
    if os.path.isdir(filepath):
        raise IsADirectoryError(f"Specified path is a directory, not a file: {filepath}")

    file_size = os.path.getsize(filepath)

    try:
        with open(filepath, "r", encoding="utf-8-sig") as f:
            content = f.read()
    except UnicodeDecodeError:
        with open(filepath, "r", encoding="latin-1") as f:
            content = f.read()

    if not content.strip():
        raise ValueError(f"Configuration file is empty: {filepath}")

    return content, file_size


def format_analyze_summary(
    static_result: dict,
    filename: str,
    verbose: bool = False,
) -> str:
    """Format concise terminal-safe text summary of analysis results."""
    config = static_result["config"]
    analysis = static_result["analysis"]
    health = static_result["health"]

    ia = config.get("input_assessment") or {}
    classification = ia.get("classification", "UNKNOWN").replace("_", " ")

    fo = ia.get("fortios") or {}
    if isinstance(fo, dict) and fo.get("detected") and fo.get("version"):
        ver_str = f"FortiOS {fo['version']}"
        if fo.get("platform"):
            ver_str += f" ({fo['platform']})"
    else:
        ver_str = "Not detected in backup header"

    policies = config.get("policies", [])
    total_policies = len(policies)
    disabled_policies = sum(
        1 for p in policies
        if isinstance(p, dict) and str(p.get("status", "")).casefold() in {"disable", "disabled"}
    )
    enabled_policies = total_policies - disabled_policies

    # Extract distinct VDOMs
    vdoms = set()
    for p in policies:
        if isinstance(p, dict) and p.get("vdom"):
            vdoms.add(str(p["vdom"]))
    vdom_count = max(len(vdoms), 1)
    vdom_str = f"{vdom_count} ({', '.join(sorted(vdoms))})" if vdoms else "1 (root)"

    # Findings
    unified_findings: list[dict] = []
    seen: set[str] = set()

    for c in health.get("checks", []):
        if isinstance(c, dict):
            key = f"HEALTH|{c.get('severity')}|{c.get('title')}|{c.get('vdom')}|{c.get('affected_object')}"
            if key not in seen:
                seen.add(key)
                unified_findings.append(c)

    for f in analysis.get("findings", []):
        if isinstance(f, dict):
            key = f"POLICY|{f.get('severity')}|{f.get('title')}|{f.get('vdom')}|{f.get('policy_id')}"
            if key not in seen:
                seen.add(key)
                unified_findings.append(f)

    sev_order = ("HIGH", "MEDIUM", "LOW", "INFO")
    counts = {s: 0 for s in sev_order}
    for f in unified_findings:
        sev = str(f.get("severity", "INFO")).upper()
        if sev in counts:
            counts[sev] += 1

    # Unresolved references
    unresolved_count = 0
    for check in health.get("checks", []):
        if check.get("title") in {
            "Unresolved Object References in Policy",
            "Referenced Security Profile Could Not Be Resolved",
            "Configuration Integrity Review Required",
        }:
            unresolved_count += len(check.get("evidence", []))

    lines = [
        "=" * 60,
        "FortiGate Static Configuration Analysis",
        "=" * 60,
        f"Source File:          {filename}",
        f"Input Classification: {classification}",
        f"FortiOS Version:      {ver_str}",
        f"VDOMs:                {vdom_str}",
        f"Firewall Policies:    {total_policies} ({enabled_policies} enabled, {disabled_policies} disabled)",
        f"Review Findings:      {len(unified_findings)} total",
        f"  - HIGH:             {counts['HIGH']}",
        f"  - MEDIUM:           {counts['MEDIUM']}",
        f"  - LOW:              {counts['LOW']}",
        f"  - INFO:             {counts['INFO']}",
        f"Unresolved Refs:      {unresolved_count}",
        "-" * 60,
    ]

    if not unified_findings:
        lines.append("No review findings were generated by the supported static checks.")
        lines.append("-" * 60)
    elif verbose:
        lines.append("Review Findings Summary:")
        for idx, f in enumerate(unified_findings, start=1):
            sev = str(f.get("severity", "INFO")).upper()
            title = f.get("title", "Observation")
            vdom = f.get("vdom") or "root"
            pid = f.get("policy_id")
            loc = f"Policy #{pid}, VDOM: {vdom}" if pid else f"VDOM: {vdom}"
            lines.append(f"  {idx}. [{sev}] {title} ({loc})")
            if f.get("description"):
                lines.append(f"     Description: {f['description']}")
            if f.get("recommendation"):
                lines.append(f"     Action:      {f['recommendation']}")
        lines.append("-" * 60)

    lines.extend([
        "Analysis Methodology & Limitations:",
        "  Static analysis evaluates configuration syntax, policy containment, and",
        "  security baseline hardening offline. Unused rules cannot be distinguished",
        "  from active policies without live session counters. Runtime connectivity,",
        "  tunnel UP/DOWN state, and hardware lifecycle dates are not verified.",
        "=" * 60,
    ])

    return "\n".join(lines)


class CLIParser(argparse.ArgumentParser):
    """Custom ArgumentParser providing clean error formatting and standard exit code 1."""

    def error(self, message: str) -> None:
        sys.stderr.write(f"Error: {message}\n\n")
        self.print_help(sys.stderr)
        sys.exit(EXIT_USAGE_ERROR)


def build_parser() -> argparse.ArgumentParser:
    """Construct standard argparse CLI parser."""
    parser = CLIParser(
        prog="fortigate-analyzer",
        description="FortiGate Security Analyzer - Static configuration review and health auditing.",
        epilog="Static analysis is performed offline and does not establish live FortiGate connectivity.",
    )
    parser.add_argument(
        "--version",
        action="version",
        version=f"fortigate-analyzer {__version__}",
    )

    subparsers = parser.add_subparsers(dest="command", metavar="COMMAND")

    # Command: analyze
    analyze_parser = subparsers.add_parser(
        "analyze",
        help="Analyze a FortiGate configuration file and print a concise terminal summary.",
    )
    analyze_parser.add_argument(
        "input",
        metavar="INPUT_FILE",
        help="Path to FortiGate exported configuration file (.conf or .txt).",
    )
    analyze_parser.add_argument(
        "-v", "--verbose",
        action="store_true",
        help="Display itemized review finding summaries in terminal output.",
    )

    # Command: export
    export_parser = subparsers.add_parser(
        "export",
        help="Export static configuration analysis to JSON or HTML report.",
    )
    export_parser.add_argument(
        "input",
        metavar="INPUT_FILE",
        help="Path to FortiGate exported configuration file (.conf or .txt).",
    )
    export_parser.add_argument(
        "--format",
        choices=["json", "html"],
        default="json",
        help="Export format: 'json' (default, schema v1.0) or 'html' (self-contained, printable).",
    )
    export_parser.add_argument(
        "-o", "--output",
        metavar="OUTPUT_FILE",
        help="Destination output file path. If omitted, JSON or HTML is printed to stdout.",
    )
    export_parser.add_argument(
        "--generated-at",
        metavar="TIMESTAMP",
        help="Explicit generation timestamp string (e.g. for deterministic testing).",
    )

    return parser


def handle_analyze(args: argparse.Namespace) -> int:
    """Execute the analyze command."""
    filepath = args.input
    try:
        config_text, file_size = read_config_file(filepath)
    except FileNotFoundError as err:
        sys.stderr.write(f"Error: {err}\n")
        return EXIT_FILE_READ_ERROR
    except (PermissionError, IsADirectoryError) as err:
        sys.stderr.write(f"Error reading file: {err}\n")
        return EXIT_FILE_READ_ERROR
    except ValueError as err:
        sys.stderr.write(f"Error: {err}\n")
        return EXIT_PROCESSING_ERROR

    filename = os.path.basename(filepath)
    static_result = run_static_analysis(config_text, metadata={"filename": filename, "file_size": file_size})

    ia = static_result["config"].get("input_assessment") or {}
    if not ia.get("fortigate_detected") and ia.get("classification") in {"UNRECOGNIZED_INPUT", "UNRECOGNIZED_FORMAT"}:
        sys.stderr.write(f"Error: Supplied file '{filename}' was not recognized as FortiGate configuration syntax.\n")
        return EXIT_PROCESSING_ERROR

    summary_text = format_analyze_summary(static_result, filename=filename, verbose=args.verbose)
    print(summary_text)
    return EXIT_SUCCESS


def handle_export(args: argparse.Namespace) -> int:
    """Execute the export command."""
    filepath = args.input
    try:
        config_text, file_size = read_config_file(filepath)
    except FileNotFoundError as err:
        sys.stderr.write(f"Error: {err}\n")
        return EXIT_FILE_READ_ERROR
    except (PermissionError, IsADirectoryError) as err:
        sys.stderr.write(f"Error reading file: {err}\n")
        return EXIT_FILE_READ_ERROR
    except ValueError as err:
        sys.stderr.write(f"Error: {err}\n")
        return EXIT_PROCESSING_ERROR

    filename = os.path.basename(filepath)
    generated_at = args.generated_at or datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    metadata = {
        "filename": filename,
        "file_size": file_size,
        "generated_at": generated_at,
    }

    static_result = run_static_analysis(config_text, metadata=metadata)

    ia = static_result["config"].get("input_assessment") or {}
    if not ia.get("fortigate_detected") and ia.get("classification") in {"UNRECOGNIZED_INPUT", "UNRECOGNIZED_FORMAT"}:
        sys.stderr.write(f"Error: Supplied file '{filename}' was not recognized as FortiGate configuration syntax.\n")
        return EXIT_PROCESSING_ERROR

    export_format = args.format.lower()

    if export_format == "json":
        projected = project_json_report(static_result, metadata=metadata)
        output_str = json.dumps(projected, indent=2, ensure_ascii=False)
    elif export_format == "html":
        output_str = generate_static_report(
            config=static_result["config"],
            analysis_result=static_result["analysis"],
            health_result=static_result["health"],
            metadata=metadata,
        )
    else:
        sys.stderr.write(f"Error: Unsupported format '{export_format}'\n")
        return EXIT_USAGE_ERROR

    if args.output:
        try:
            with open(args.output, "w", encoding="utf-8") as f:
                f.write(output_str)
            sys.stderr.write(f"Report successfully exported to {args.output}\n")
        except OSError as err:
            sys.stderr.write(f"Error writing to output file '{args.output}': {err}\n")
            return EXIT_FILE_READ_ERROR
    else:
        # Print directly to stdout with NO diagnostic pollution
        sys.stdout.write(output_str)
        if not output_str.endswith("\n"):
            sys.stdout.write("\n")

    return EXIT_SUCCESS


def main(argv: Sequence[str] | None = None) -> int:
    """CLI application entry point."""
    parser = build_parser()

    if argv is None:
        argv = sys.argv[1:]

    if not argv:
        parser.print_help(sys.stderr)
        return EXIT_USAGE_ERROR

    # Parse arguments
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return exc.code if isinstance(exc.code, int) else EXIT_USAGE_ERROR

    if args.command == "analyze":
        return handle_analyze(args)
    elif args.command == "export":
        return handle_export(args)
    else:
        parser.print_help(sys.stderr)
        return EXIT_USAGE_ERROR


if __name__ == "__main__":
    sys.exit(main())
